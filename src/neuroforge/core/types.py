# Diagnostics (physics checker output) and solve result
# --------------------------------------------------------------------------- #


@dataclass
class Diagnostics:
    """Self-assessment of a predicted field: residuals, uncertainty, trust.

    All maps are ``(ny, nx)`` float32. ``trust`` is in ``[0, 1]`` (1 = reliable).
    ``trust_class`` is an integer map: 2 = green (reliable), 1 = yellow
    (acceptable), 0 = red (needs correction/refinement).
    """

    continuity: np.ndarray
    momentum_x: np.ndarray
    momentum_y: np.ndarray
    bc_violation: np.ndarray
    uncertainty: np.ndarray
    trust: np.ndarray
    trust_class: np.ndarray
    summary: dict[str, float] = field(default_factory=dict)

    def residual_norm(self) -> float:
        """Scalar L2 residual magnitude used as the convergence signal."""
        r = np.sqrt(self.continuity ** 2 + self.momentum_x ** 2 + self.momentum_y ** 2)
        return float(np.sqrt(np.mean(r ** 2)))


@dataclass
class SolveResult:
    """The full output of :meth:`NeuroForgeEngine.solve`."""

    case: FlowCase
    field: FlowField
    diagnostics: Diagnostics
    metrics: dict[str, float] = field(default_factory=dict)
    history: list[dict[str, float]] = field(default_factory=list)
    meta: dict[str, Any] = field(default_factory=dict)

    def save_report(self, path: str, **kwargs: Any) -> str:
        """Render an HTML/PNG report. Lazily imports :mod:`neuroforge.viz.report`."""
        from neuroforge.viz.report import build_report  # lazy
        return build_report(self, path, **kwargs)

    def summary(self) -> dict[str, float]:
        out = dict(self.metrics)
        out["residual_norm"] = self.diagnostics.residual_norm()
        out["n_iters"] = float(len(self.history))
        return out
